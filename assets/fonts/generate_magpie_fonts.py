#!/usr/bin/env python3
"""Generate the fixed dashboard subsets in LVGL 9's uncompressed A4 format."""

import argparse
import hashlib
from pathlib import Path

from fontTools.ttLib import TTFont
from PIL import ImageFont, features


DIRECTORY = Path(__file__).resolve().parent
SOURCE_SHA256 = "2c76254f6fc379fddfce0a7e84fb5385bb135d3e399294f6eeb6680d0365b74b"
ASCII = range(0x20, 0x7F)
SIZES = (14, 22)


def inventory():
    sections = {}
    for line in (DIRECTORY / "magpie_glyphs.txt").read_text(encoding="utf-8").splitlines():
        if line.startswith("["):
            active = int(line[1:-1])
            sections[active] = set()
        elif line and not line.startswith("#"):
            sections[active].update(ord(character) for character in line if ord(character) >= 0x80)
    if set(sections) != set(SIZES) or any(not points for points in sections.values()):
        raise ValueError("Expected a nonempty character inventory for each font size")
    return sections


def c_array(values, digits):
    return "\n".join(
        "    " + ", ".join(f"0x{value:0{digits}x}" for value in values[index:index + 12]) + ","
        for index in range(0, len(values), 12)
    )


def render(source, size, cjk):
    raster = ImageFont.truetype(source, size, layout_engine=ImageFont.Layout.BASIC)
    bitmap = bytearray()
    descriptors = ["    {0},"]
    ascent = 0
    descent = 0
    for codepoint in [*ASCII, *cjk]:
        character = chr(codepoint)
        mask, (left, top) = raster.getmask2(character, mode="L", anchor="ls")
        width, height = mask.size
        if height and not any(mask):
            raise ValueError(f"No ink for U+{codepoint:04X}")
        advance = round(raster.getlength(character) * 16)
        bottom = top + height
        ascent = max(ascent, -top)
        descent = max(descent, bottom)
        descriptors.append(
            f"    {{{len(bitmap)}, {advance}, {width}, {height}, {left}, {-bottom}}}, "
            f"/* U+{codepoint:04X} */"
        )
        # A glyph starts at byte alignment; its rows remain contiguous.
        alphas = [(value * 15 + 127) // 255 for value in mask]
        if len(alphas) % 2:
            alphas.append(0)
        bitmap.extend((alphas[index] << 4) | alphas[index + 1]
                      for index in range(0, len(alphas), 2))

    cjk_start = cjk[0]
    cjk_offsets = [value - cjk_start for value in cjk]
    glyph_rows = "\n".join(descriptors)
    return f"""/* Generated by generate_magpie_fonts.py. Do not edit.
 * Derived from Noto Sans CJK SC Regular 2.004.
 * Copyright 2014-2021 Adobe (http://www.adobe.com/).
 * SPDX-License-Identifier: OFL-1.1
 */

#include "lvgl.h"

static const uint8_t glyph_bitmap[] = {{
{c_array(bitmap, 2)}
}};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{glyph_rows}
}};

static const uint16_t cjk_offsets[] = {{
{c_array(cjk_offsets, 4)}
}};

static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{
        .range_start = 0x20, .range_length = {len(ASCII)}, .glyph_id_start = 1,
        .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY,
    }},
    {{
        .range_start = 0x{cjk_start:04x}, .range_length = {cjk_offsets[-1] + 1},
        .glyph_id_start = {1 + len(ASCII)}, .unicode_list = cjk_offsets, .list_length = {len(cjk)},
        .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY,
    }},
}};

static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .cmap_num = 2,
    .bpp = 4,
    .bitmap_format = LV_FONT_FMT_TXT_PLAIN,
}};

const lv_font_t magpie_cjk_{size} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {ascent + descent},
    .base_line = {descent},
    .dsc = &font_dsc,
}};
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="NotoSansCJKsc-Regular.otf from Sans2.004")
    parser.add_argument("--check", action="store_true", help="verify existing generated output")
    args = parser.parse_args()
    if features.version_module("freetype2") != "2.14.3":
        parser.error("Use the pinned Pillow 12.2.0 wheel with FreeType 2.14.3")
    if hashlib.sha256(args.source.read_bytes()).hexdigest() != SOURCE_SHA256:
        parser.error("Source font SHA-256 does not match Noto Sans CJK SC Regular 2.004")
    sections = inventory()
    with TTFont(args.source, lazy=True) as font:
        cmap = font.getBestCmap()
        for size in SIZES:
            missing = (set(ASCII) | sections[size]) - cmap.keys()
            if missing:
                parser.error(f"{size}px missing source glyphs: {', '.join(f'U+{cp:04X}' for cp in sorted(missing))}")
            target = DIRECTORY / f"magpie_cjk_{size}.c"
            result = render(args.source, size, sorted(sections[size])).encode("utf-8")
            if args.check:
                if target.read_bytes() != result:
                    parser.error(f"{target.name} does not match generated output")
            else:
                target.write_bytes(result)


if __name__ == "__main__":
    main()
